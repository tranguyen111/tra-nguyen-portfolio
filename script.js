const modal = document.getElementById("case-modal");
const modalContent = document.getElementById("modal-content");
const modalClose = document.getElementById("modal-close");

document.querySelectorAll(".open-modal").forEach((btn) => {
  btn.addEventListener("click", () => {
    const data = CASE_STUDIES[btn.dataset.project];
    if (!data) return;
    modalContent.innerHTML = `
      <span class="eyebrow">${data.industry}</span>
      <h2>${data.title}</h2>
      <img class="modal-hero-img" src="${data.image}" alt="${data.title}" onerror="this.style.display='none'" />
      <div class="modal-section">
        <h4>Bối cảnh & Thách thức</h4>
        <p>${data.challenge}</p>
      </div>
      <div class="modal-section">
        <h4>Giải pháp & Đầu việc</h4>
        <ul>${data.deliverables.map((item) => `<li>${item}</li>`).join("")}</ul>
      </div>
      <div class="modal-section">
        <h4>Mẫu Copywriting & Kịch bản thực tế</h4>
        <div class="copy-sample-box">${data.copySample}</div>
      </div>
      <div class="modal-section">
        <h4>Kết quả đạt được</h4>
        <p><strong>${data.results}</strong></p>
      </div>
    `;
    modal.classList.add("open");
    modal.setAttribute("aria-hidden", "false");
  });
});

modalClose.addEventListener("click", () => {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
});

modal.addEventListener("click", (e) => {
  if (e.target === modal) {
    modal.classList.remove("open");
    modal.setAttribute("aria-hidden", "true");
  }
});

// LinkedIn Kit render & copy
const kitContainer = document.getElementById("kit-container");
const toast = document.getElementById("toast");

function showToast(msg = "Đã copy vào clipboard!") {
  toast.textContent = msg;
  toast.classList.add("show");
  setTimeout(() => toast.classList.remove("show"), 2200);
}

LINKEDIN_KIT.forEach((item) => {
  const card = document.createElement("div");
  card.className = "kit-card";
  card.innerHTML = `
    <div class="kit-card-head">
      <h3>${item.title}</h3>
      <button class="copy-btn">Copy</button>
    </div>
    <div class="kit-preview">${item.text}</div>
  `;
  card.querySelector(".copy-btn").addEventListener("click", async () => {
    try {
      await navigator.clipboard.writeText(item.text);
      showToast(`Đã copy "${item.title}"!`);
    } catch {
      showToast("Không thể tự động copy, hãy bôi đen thủ công.");
    }
  });
  kitContainer.appendChild(card);
});
